function changeLanguage(language) {
  const dictionary = translations[language];

  if (!dictionary) return;

  document.documentElement.lang = language;

  document.querySelectorAll("[data-translate]").forEach((element) => {
    const key = element.dataset.translate;

    if (!Object.prototype.hasOwnProperty.call(dictionary, key)) {
      console.warn("Missing translation:", language, key);
      return;
    }

    // Keep the heading's line break and highlighted span.
    if (key === "heading") {
      element.innerHTML = dictionary[key];
    } else {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-translate-placeholder]").forEach((element) => {
    const key = element.dataset.translatePlaceholder;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-translate-aria]").forEach((element) => {
    const key = element.dataset.translateAria;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  try {
    localStorage.setItem("smartlab-language", language);
  } catch (error) {
    // Language switching still works if local storage is unavailable.
  }
}

function initializeLanguageSelector() {
  const selector = document.getElementById("languageSelect");

  if (!selector) return;

  selector.addEventListener("change", function () {
    changeLanguage(this.value);
  });

  let initialLanguage = "en";

  try {
    const savedLanguage = localStorage.getItem("smartlab-language");

    if (savedLanguage && translations[savedLanguage]) {
      initialLanguage = savedLanguage;
    }
  } catch (error) {
    // Use English if local storage is unavailable.
  }

  selector.value = initialLanguage;
  changeLanguage(initialLanguage);
}

function showSearchMessage(key) {
  const selector = document.getElementById("languageSelect");
  const language =
    selector && translations[selector.value] ? selector.value : "en";

  const message = document.getElementById("searchMessage");

  if (message) {
    message.textContent = translations[language][key] || "";
  }
}

function initializeSearch() {
  const searchButton = document.getElementById("searchButton");
  const labSearch = document.getElementById("labSearch");

  if (!searchButton || !labSearch) return;

  searchButton.addEventListener("click", function () {
    const query = labSearch.value.trim();

    if (!query) {
      showSearchMessage("searchEmpty");
      labSearch.focus();
      return;
    }

    const labSection = document.getElementById("labs");

    if (labSection) {
      labSection.scrollIntoView({ behavior: "smooth" });
    }

    showSearchMessage("searchDemo");
  });

  labSearch.addEventListener("keydown", function (event) {
    if (event.key === "Enter") {
      searchButton.click();
    }
  });
}

function initializeSmartLab() {
  initializeLanguageSelector();
  initializeSearch();
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initializeSmartLab);
} else {
  initializeSmartLab();
}
