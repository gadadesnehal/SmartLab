const languageSelect = document.getElementById("languageSelect");
console.log("Language dropdown:", languageSelect);

function changeLanguage(language) {
  const dictionary = translations[language];

  if (!dictionary) return;

  document.documentElement.lang = language;

  document.querySelectorAll("[data-translate]").forEach((element) => {
    const key = element.dataset.translate;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-translate-placeholder]").forEach((element) => {
    const key = element.dataset.translatePlaceholder;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-translate-aria]").forEach((element) => {
    const key = element.dataset.translateAria;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  try {
    localStorage.setItem("smartlab-language", language);
  } catch (error) {
    // Translation still works if storage is unavailable.
  }
}

if (languageSelect) {
  languageSelect.addEventListener("change", (event) => {
    changeLanguage(event.target.value);
  });

  let initialLanguage = "en";

  try {
    const savedLanguage = localStorage.getItem("smartlab-language");

    if (savedLanguage && translations[savedLanguage]) {
      initialLanguage = savedLanguage;
    }
  } catch (error) {
    // Use English if browser storage is unavailable.
  }

  languageSelect.value = initialLanguage;
  changeLanguage(initialLanguage);
}

const searchButton = document.getElementById("searchButton");
const labSearch = document.getElementById("labSearch");
const searchMessage = document.getElementById("searchMessage");

function showSearchMessage(key) {
  const language = languageSelect && translations[languageSelect.value]
    ? languageSelect.value
    : "en";

  if (searchMessage) {
    searchMessage.textContent = translations[language][key] || "";
  }
}

if (searchButton && labSearch && searchMessage) {
  searchButton.addEventListener("click", () => {
    const query = labSearch.value.trim();

    if (!query) {
      showSearchMessage("searchEmpty");
      labSearch.focus();
      return;
    }

    const labSection = document.getElementById("labs");

    if (labSection) {
      labSection.scrollIntoView({ behavior: "smooth" });
    }

    showSearchMessage("searchDemo");
  });

  labSearch.addEventListener("keydown", (event) => {
    if (event.key === "Enter") {
      searchButton.click();
    }
  });
}
